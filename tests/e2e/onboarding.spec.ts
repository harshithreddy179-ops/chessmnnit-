import { test, expect } from "./fixtures";

/**
 * The student journey: Google sign-in (simulated by a session cookie) -> eligibility ->
 * Chess.com ownership verification -> finished registration. Chess.com itself is a local
 * stand-in modelled on the documented API; everything else is the real application.
 */
test.describe("onboarding", () => {
  test("a student not on the list asks for review, an administrator approves, then ownership is proven with a code", async ({
    db,
    chess,
    pageAs,
  }) => {
    const user = await db.createUser({ name: "Nia Newcomer" });
    const page = await pageAs(user);

    await page.goto("/dashboard");
    await expect(page).toHaveURL(/\/onboarding/);
    await expect(page.getByRole("heading", { name: "Welcome to the club" })).toBeVisible();

    // The four facts are shown separately; only the Google sign-in is true so far.
    const checklist = page.getByRole("list", { name: "Verification status" });
    await expect(
      checklist
        .getByRole("listitem")
        .filter({ hasText: "Google account signed in" })
        .getByLabel("Complete"),
    ).toBeVisible();
    await expect(
      checklist
        .getByRole("listitem")
        .filter({ hasText: "College eligibility verified" })
        .getByLabel("Not done"),
    ).toBeVisible();
    await expect(
      checklist
        .getByRole("listitem")
        .filter({ hasText: "Chess.com ownership verified" })
        .getByLabel("Not done"),
    ).toBeVisible();

    // Not on the allowlist -> manual review route (no pretending).
    await expect(page.getByText("isn’t on the approved student list yet").first()).toBeVisible();
    await expect(page.getByText("Confirm you’re a student first")).toBeVisible(); // Chess.com step is locked until eligible
    await page.getByLabel(/Roll number or college email/).fill("2024CA17");
    await page.getByRole("button", { name: "Request review" }).click();
    await expect(page.getByText("Waiting for an administrator")).toBeVisible();
    expect(
      (
        await db.admin.query(
          "select claimed_identifier from public.eligibility_requests where user_id = $1",
          [user.id],
        )
      ).rows[0].claimed_identifier,
    ).toBe("2024CA17");

    // A verification administrator approves it.
    const admin = await db.createUser({ name: "Vera Admin" });
    await db.makeAdmin(admin.id, "verification_admin");
    const req = (
      await db.admin.query("select id from public.eligibility_requests where user_id = $1", [
        user.id,
      ])
    ).rows[0];
    await db
      .as(admin.id)
      .query(
        "select * from public.admin_review_eligibility_request($1, true, 'Roll number matches the department list')",
        [req.id],
      );

    await page.reload();
    await expect(page.getByText("You’re on the approved student list")).toBeVisible();

    // Chess.com: the code is generated by the database, shown to the student, and must appear on their public profile.
    chess.setProfile({ username: "nia_chess", player_id: 31337, location: "Prayagraj" });
    chess.setStats("nia_chess", {
      chess_rapid: {
        last: { rating: 1337, date: 1_760_000_000 },
        best: { rating: 1400 },
        record: { win: 5, loss: 4, draw: 1 },
      },
    });
    await page.getByLabel(/Chess\.com username/).fill("https://www.chess.com/member/Nia_Chess");
    await page.getByRole("button", { name: "Start verification" }).click();
    const codeEl = page.locator("code", { hasText: /^MNNIT-/ });
    await expect(codeEl).toBeVisible();
    const code = (await codeEl.textContent())!.trim();
    expect(code).toMatch(/^MNNIT-[A-HJKMNP-Z2-9]{8}$/);

    // Before the profile contains the code: honest failure, nothing linked.
    await page.getByRole("button", { name: "Check my profile" }).click();
    await expect(
      page.getByText(/could not see the code on your public Chess\.com profile yet/),
    ).toBeVisible();
    expect(
      (
        await db.admin.query(
          "select count(*)::int as n from public.chess_account_links where user_id = $1",
          [user.id],
        )
      ).rows[0].n,
    ).toBe(0);

    // The student edits their Chess.com location; the server now reads it from the public API.
    chess.setProfile({ username: "nia_chess", player_id: 31337, location: `Allahabad ${code}` });
    await page.getByRole("button", { name: "Check my profile" }).click();
    await expect(page.getByText(/Verified: /)).toBeVisible();
    await expect(page.getByText("@nia_chess").first()).toBeVisible();

    const link = (
      await db.admin.query(
        "select chess_username, chess_player_id::int as pid, verification_method from public.chess_account_links where user_id = $1",
        [user.id],
      )
    ).rows[0];
    expect(link).toEqual({
      chess_username: "nia_chess",
      pid: 31337,
      verification_method: "profile_code",
    });
    // The first rating import ran right after verification.
    expect(
      (
        await db.admin.query(
          "select rating from public.chess_ratings where user_id = $1 and time_class = 'rapid'",
          [user.id],
        )
      ).rows[0].rating,
    ).toBe(1337);

    // Finish: now all four facts hold and the player is public.
    await page.getByRole("button", { name: "Complete registration" }).click();
    await expect(page).toHaveURL(/\/dashboard/);
    await expect(page.getByText("1337")).toBeVisible();
    expect(
      (await db.admin.query("select is_approved from public.profiles where id = $1", [user.id]))
        .rows[0].is_approved,
    ).toBe(true);
    await page.goto("/players/nia_chess");
    await expect(page.getByRole("heading", { name: "Nia Newcomer" })).toBeVisible();
  });

  test("rejects malformed usernames and accounts that do not exist on Chess.com", async ({
    db,
    pageAs,
  }) => {
    const u = await db.createUser({ name: "Eli Eligible" });
    await db.allowEmail(u.email);
    const page = await pageAs(u);
    await page.goto("/onboarding");
    await page.getByLabel(/Chess\.com username/).fill("no spaces allowed!");
    await page.getByRole("button", { name: "Start verification" }).click();
    await expect(page.getByText(/Enter a valid Chess\.com username/)).toBeVisible();
    await page.getByLabel(/Chess\.com username/).fill("ghost_account_xyz");
    await page.getByRole("button", { name: "Start verification" }).click();
    await expect(
      page.getByText(/No Chess\.com account named "ghost_account_xyz" was found/),
    ).toBeVisible();
    expect(
      (
        await db.admin.query(
          "select count(*)::int as n from public.chess_link_claims where user_id = $1",
          [u.id],
        )
      ).rows[0].n,
    ).toBe(0);
  });

  test("falls back to administrator review when the code cannot be seen, and the admin decision is audited", async ({
    db,
    chess,
    pageAs,
  }) => {
    const student = await db.createUser({ name: "Sam Student" });
    await db.allowEmail(student.email);
    chess.setProfile({ username: "sam_cached", player_id: 4242, location: "stale cached value" });
    const page = await pageAs(student);
    await page.goto("/onboarding");
    await page.getByLabel(/Chess\.com username/).fill("sam_cached");
    await page.getByRole("button", { name: "Start verification" }).click();
    await page.getByRole("button", { name: "Ask an administrator instead" }).click();
    await page
      .getByLabel(/How can an administrator confirm/)
      .fill("Chess.com has not refreshed my profile; I can show the account at the club room.");
    await page.getByRole("button", { name: "Send for review" }).click();
    await expect(
      page.getByText("Waiting for an administrator to verify @sam_cached"),
    ).toBeVisible();

    const admin = await db.createUser({ name: "Vera Verifier" });
    await db.makeAdmin(admin.id, "verification_admin");
    const adminPage = await pageAs(admin);
    await adminPage.goto("/admin/verifications");
    await expect(adminPage.getByText("show the account at the club room")).toBeVisible();
    await adminPage.getByRole("button", { name: "Approve" }).first().click();
    await adminPage
      .getByLabel("How did you confirm ownership?")
      .fill("Checked the live account with the student at the club room");
    await adminPage.getByRole("button", { name: "Confirm" }).click();
    await expect(adminPage.getByText("No claims waiting")).toBeVisible();

    const link = (
      await db.admin.query(
        "select chess_username, chess_player_id::int as pid, verification_method from public.chess_account_links where user_id = $1",
        [student.id],
      )
    ).rows[0];
    expect(link).toEqual({
      chess_username: "sam_cached",
      pid: 4242,
      verification_method: "admin_review",
    });
    await adminPage.goto("/admin/audit?action=chess_link.");
    // The audit log is shared by every test in this run, so identify the entry by its reason text.
    await expect(adminPage.getByText("chess_link.verified").first()).toBeVisible();
    await expect(
      adminPage.getByText("Checked the live account with the student at the club room").first(),
    ).toBeVisible();
    const audit = (
      await db.admin.query(
        "select actor_id, actor_kind, reason from public.audit_logs where action = 'chess_link.verified' and after_data->>'user_id' = $1",
        [student.id],
      )
    ).rows;
    expect(audit).toEqual([
      {
        actor_id: admin.id,
        actor_kind: "admin",
        reason: "Checked the live account with the student at the club room",
      },
    ]);
    // The student is told.
    expect(
      (
        await db
          .as(student.id)
          .query("select title from public.notifications where type = 'verification_result'")
      ).rows[0].title,
    ).toBe("Chess.com account verified");
  });

  test("a Chess.com username already verified for someone else can never be claimed", async ({
    db,
    chess,
    player,
    pageAs,
  }) => {
    const owner = await player({ username: "taken_name" });
    chess.setProfile({ username: "taken_name", player_id: owner.playerId, location: "Allahabad" });
    const rival = await db.createUser({ name: "Rick Rival" });
    await db.allowEmail(rival.email);
    const page = await pageAs(rival);
    await page.goto("/onboarding");
    await page.getByLabel(/Chess\.com username/).fill("taken_name");
    await page.getByRole("button", { name: "Start verification" }).click();
    const code = (await page.locator("code", { hasText: /^MNNIT-/ }).textContent())!.trim();
    // Even if the code were visible on the profile (the real owner would have to put it there),
    // the one-to-one rule rejects the claim.
    chess.setProfile({ username: "taken_name", player_id: owner.playerId, location: code });
    await page.getByRole("button", { name: "Check my profile" }).click();
    await expect(page.getByText(/already linked to another member/)).toBeVisible();
    expect(
      (
        await db.admin.query(
          "select user_id from public.chess_account_links where chess_username = 'taken_name'",
        )
      ).rows.map((r) => r.user_id),
    ).toEqual([owner.id]);
  });
});
